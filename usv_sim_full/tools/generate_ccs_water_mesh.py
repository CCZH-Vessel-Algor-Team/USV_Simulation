#!/usr/bin/env python3
"""Generate the single, graded CCS render mesh (no runtime generator)."""

from itertools import islice
from math import ceil
from pathlib import Path


# Half width and nominal spacing, in metres, shared with the vertex shader.
LEVELS = (
    (96, 3), (384, 6), (576, 12), (864, 24), (1440, 48), (1920, 96),
    (3072, 192), (4608, 384), (6912, 768), (12288, 1536), (18000, 3072),
)
OUTPUT = (
    Path(__file__).resolve().parents[1] /
    'worlds/models/ccs_water/meshes/ccs_water.dae'
)


def square_ring(radius, spacing):
    segments = ceil(2 * radius / spacing)
    offsets = [-radius + 2 * radius * i / segments for i in range(segments)]
    # Counterclockwise, with each corner included exactly once.
    return (
        [(p, -radius) for p in offsets] + [(radius, p) for p in offsets] +
        [(-p, radius) for p in offsets] + [(-radius, -p) for p in offsets]
    )


def stitch(inner_start, inner_count, outer_start, outer_count):
    """Join unequal sides without T-junctions or overlapping water surfaces."""
    for side in range(4):
        i, j = 0, 0
        while i < inner_count or j < outer_count:
            inner = inner_start + (side * inner_count + i) % (4 * inner_count)
            outer = outer_start + (side * outer_count + j) % (4 * outer_count)
            if j == outer_count or (
                i < inner_count and (i + 1) * outer_count <= (j + 1) * inner_count
            ):
                index = (side * inner_count + i + 1) % (4 * inner_count)
                yield inner, outer, inner_start + index
                i += 1
            else:
                index = (side * outer_count + j + 1) % (4 * outer_count)
                yield inner, outer, outer_start + index
                j += 1


def generate():
    vertices = [(0, 0)]
    triangles = []
    inner_start, inner_count, previous_radius = 0, 0, 0
    for limit, spacing in LEVELS:
        radii = [*range(previous_radius + spacing, limit, spacing), limit]
        for radius in radii:
            ring = square_ring(radius, spacing)
            outer_start, outer_count = len(vertices), len(ring) // 4
            vertices.extend(ring)
            if inner_count:
                triangles.extend(stitch(inner_start, inner_count, outer_start, outer_count))
            else:
                triangles.extend(
                    (0, outer_start + i, outer_start + (i + 1) % len(ring))
                    for i in range(len(ring))
                )
            inner_start, inner_count = outer_start, outer_count
        previous_radius = limit
    return vertices, triangles


def write_rows(out, entries):
    entries = iter(entries)
    while row := list(islice(entries, 12)):
        out.write(' '.join(row) + '\n')


def write_collada(path, vertices, triangles):
    count = len(vertices)
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open('w', encoding='utf-8', newline='\n') as out:
        out.write(f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/generate_ccs_water_mesh.py. -->
<COLLADA xmlns="http://www.collada.org/2005/11/COLLADASchema" version="1.4.1">
  <asset><unit meter="1" name="meter"/><up_axis>Z_UP</up_axis></asset>
  <library_geometries><geometry id="water" name="water"><mesh>
    <source id="positions">
      <float_array id="positions-array" count="{3 * count}">
''')
        write_rows(out, (f'{x:.10g} {y:.10g} 0' for x, y in vertices))
        out.write(f'''</float_array>
      <technique_common><accessor source="#positions-array" count="{count}" stride="3">
        <param name="X" type="float"/><param name="Y" type="float"/><param name="Z" type="float"/>
      </accessor></technique_common>
    </source>
    <source id="normals">
      <float_array id="normals-array" count="3">0 0 1</float_array>
      <technique_common><accessor source="#normals-array" count="1" stride="3">
        <param name="X" type="float"/><param name="Y" type="float"/><param name="Z" type="float"/>
      </accessor></technique_common>
    </source>
    <vertices id="vertices"><input semantic="POSITION" source="#positions"/></vertices>
    <triangles count="{len(triangles)}">
      <input semantic="VERTEX" source="#vertices" offset="0"/>
      <input semantic="NORMAL" source="#normals" offset="1"/>
      <p>
''')
        write_rows(out, (' '.join(f'{i} 0' for i in tri) for tri in triangles))
        out.write('''</p>
    </triangles>
  </mesh></geometry></library_geometries>
  <library_visual_scenes><visual_scene id="Scene">
    <node id="water-node" name="water"><instance_geometry url="#water"/></node>
  </visual_scene></library_visual_scenes>
  <scene><instance_visual_scene url="#Scene"/></scene>
</COLLADA>
''')


if __name__ == '__main__':
    write_collada(OUTPUT, *generate())
